CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    patronymic VARCHAR(50),
    last_name VARCHAR(50) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    registration_date DATE NOT NULL DEFAULT CURRENT_DATE,

    CONSTRAINT chk_user_email
        CHECK (POSITION('@' IN email) > 1)
);

CREATE TABLE citizenship (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE country (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE city (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    country_id INTEGER NOT NULL REFERENCES country(id),

    CONSTRAINT uq_city_country UNIQUE (name, country_id)
);

CREATE TABLE airport (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    airport_code VARCHAR(10) NOT NULL UNIQUE,
    city_id INTEGER NOT NULL REFERENCES city(id)
);

CREATE TABLE flight_status (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE service_class (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE passenger (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id),
    date_of_birth DATE NOT NULL,
    phone VARCHAR(20),
    gender BOOLEAN,

    CONSTRAINT chk_passenger_birth
        CHECK (date_of_birth <= CURRENT_DATE)
);

CREATE TABLE passport (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    passenger_id INTEGER NOT NULL REFERENCES passenger(id),
    citizenship_id INTEGER NOT NULL REFERENCES citizenship(id),
    document_number VARCHAR(50) NOT NULL,
    passport_type VARCHAR(50) NOT NULL,

    CONSTRAINT uq_passport
        UNIQUE (citizenship_id, passport_type, document_number),

    CONSTRAINT uq_passport_passenger
        UNIQUE (id, passenger_id)
);

CREATE TABLE flight (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_number VARCHAR(20) NOT NULL,
    departure_airport_id INTEGER NOT NULL REFERENCES airport(id),
    arrival_airport_id INTEGER NOT NULL REFERENCES airport(id),
    departure_datetime TIMESTAMP NOT NULL,
    arrival_datetime TIMESTAMP NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    flight_status_id INTEGER NOT NULL REFERENCES flight_status(id),

    CONSTRAINT chk_flight_airports
        CHECK (departure_airport_id <> arrival_airport_id),

    CONSTRAINT chk_flight_dates
        CHECK (arrival_datetime > departure_datetime),

    CONSTRAINT chk_flight_price
        CHECK (price >= 0),

    CONSTRAINT uq_flight
        UNIQUE (flight_number, departure_datetime)
);

CREATE TABLE air_ticket (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    passenger_id INTEGER NOT NULL REFERENCES passenger(id),
    flight_id INTEGER NOT NULL REFERENCES flight(id),
    service_class_id INTEGER NOT NULL REFERENCES service_class(id),
    place VARCHAR(5) NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    date_of_execution DATE NOT NULL DEFAULT CURRENT_DATE,
    passport_id INTEGER NOT NULL,

    CONSTRAINT fk_ticket_passport
        FOREIGN KEY (passport_id, passenger_id)
        REFERENCES passport(id, passenger_id),

    CONSTRAINT chk_ticket_price
        CHECK (price >= 0),

    CONSTRAINT uq_flight_place
        UNIQUE (flight_id, place)
);